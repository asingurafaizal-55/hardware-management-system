    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer[] k = keys();
if (k == null) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "INSERT INTO supplier_hardware (supplier_id, hardware_id, supply_price, lead_time_days) "
        + "VALUES (?, ?, ?, ?) AS v ON DUPLICATE KEY UPDATE "
        + "supply_price=v.supply_price, lead_time_days=v.lead_time_days")) {
    ps.setInt(1, k[0]);
    ps.setInt(2, k[1]);
    ps.setString(3, txtSupplyPrice.getText().trim());
    ps.setString(4, txtLeadTime.getText().trim());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer[] k = keys();
if (k == null) return;
int confirm = JOptionPane.showConfirmDialog(this, "Delete this record?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "DELETE FROM supplier_hardware WHERE supplier_id=? AND hardware_id=?")) {
    ps.setInt(1, k[0]);
    ps.setInt(2, k[1]);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
       // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

