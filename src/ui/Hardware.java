    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer id = currentId();
Integer catId = comboId(cmbCategory);
Integer brandId = comboId(cmbBrand);
if (id == null || txtName.getText().trim().isEmpty() || catId == null || brandId == null) {
    JOptionPane.showMessageDialog(this, "Enter a numeric Hardware ID and a name, and choose a category and brand");
    return;
}
java.math.BigDecimal price;
try {
    price = new java.math.BigDecimal(txtPrice.getText().trim());
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Unit price must be a number, for example 450.00");
    return;
}
try (Connection con = DBConnection.getConnection()) {
    PreparedStatement up = con.prepareStatement(
        "UPDATE hardware SET category_id=?, brand_id=?, hardware_name=?, model=?, unit_price=?, status=? WHERE hardware_id=?");
    up.setInt(1, catId);
    up.setInt(2, brandId);
    up.setString(3, txtName.getText().trim());
    up.setString(4, txtModel.getText().trim());
    up.setBigDecimal(5, price);
    up.setString(6, txtStatus.getText().trim());
    up.setInt(7, id);
    if (up.executeUpdate() == 0) {
        PreparedStatement ins = con.prepareStatement(
            "INSERT INTO hardware (hardware_id, category_id, brand_id, hardware_name, model, unit_price, status) VALUES (?, ?, ?, ?, ?, ?, ?)");
        ins.setInt(1, id);
        ins.setInt(2, catId);
        ins.setInt(3, brandId);
        ins.setString(4, txtName.getText().trim());
        ins.setString(5, txtModel.getText().trim());
        ins.setBigDecimal(6, price);
        ins.setString(7, txtStatus.getText().trim());
        ins.executeUpdate();
    }
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer id = currentId();
if (id == null) {
    JOptionPane.showMessageDialog(this, "Find or select a record first");
    return;
}
int confirm = JOptionPane.showConfirmDialog(this, "Delete this hardware?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement("DELETE FROM hardware WHERE hardware_id=?")) {
    ps.setInt(1, id);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

