private void openFrame(JFrame f) {
    f.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
    f.setLocationRelativeTo(null);
    f.setVisible(true);
}

private void addItem(JMenu menu, String text, java.util.function.Supplier<JFrame> maker) {
    JMenuItem item = new JMenuItem(text);
    item.addActionListener(e -> openFrame(maker.get()));
    menu.add(item);
}

private void buildData(String role) {
    JMenu products = new JMenu("Products");
    addItem(products, "Category", () -> new Category());
    addItem(products, "Brand", () -> new Brand());
    addItem(products, "Hardware", () -> new Hardware());
    addItem(products, "Specification", () -> new Specification());
    addItem(products, "Stock", () -> new Stock());
    addItem(products, "Warranty", () -> new Warranty());
    menuData.add(products);

    JMenu people = new JMenu("People");
    addItem(people, "Supplier", () -> new Supplier());
    addItem(people, "Customer", () -> new Customer());
    addItem(people, "Employee", () -> new Employee());
    if (role != null && role.equalsIgnoreCase("Admin")) {
        addItem(people, "User Accounts", () -> new UserAccount());
    }
    menuData.add(people);

    JMenu purchasing = new JMenu("Purchasing");
    addItem(purchasing, "Supplier Hardware", () -> new SupplierHardware());
    addItem(purchasing, "Purchase", () -> new Purchase());
    addItem(purchasing, "Purchase Detail", () -> new PurchaseDetail());
    menuData.add(purchasing);

    JMenu sales = new JMenu("Sales and Service");
    addItem(sales, "Sale", () -> new Sale());
    addItem(sales, "Sale Detail", () -> new SaleDetail());
    addItem(sales, "Payment", () -> new Payment());
    addItem(sales, "Repair", () -> new Repair());
    menuData.add(sales);
}    





