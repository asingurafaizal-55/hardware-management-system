    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer id = currentId();
Integer hwId = comboId(cmbHardware);
Integer custId = comboId(cmbCustomer);
Integer empId = comboId(cmbEmployee);
if (id == null || hwId == null || custId == null || empId == null) {
    JOptionPane.showMessageDialog(this, "Enter a numeric Repair ID and choose hardware, customer and employee");
    return;
}
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "INSERT INTO repair (repair_id, hardware_id, customer_id, employee_id, repair_date, "
        + "problem_description, repair_cost, repair_status) VALUES (?, ?, ?, ?, ?, ?, ?, ?) AS v "
        + "ON DUPLICATE KEY UPDATE hardware_id=v.hardware_id, customer_id=v.customer_id, "
        + "employee_id=v.employee_id, repair_date=v.repair_date, "
        + "problem_description=v.problem_description, repair_cost=v.repair_cost, "
        + "repair_status=v.repair_status")) {
    ps.setInt(1, id);
    ps.setInt(2, hwId);
    ps.setInt(3, custId);
    ps.setInt(4, empId);
    ps.setString(5, txtDate.getText().trim());
    ps.setString(6, txtProblem.getText().trim());
    ps.setString(7, txtCost.getText().trim());
    ps.setString(8, txtStatus.getText().trim());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer id = currentId();
if (id == null) {
    JOptionPane.showMessageDialog(this, "Find or select a record first");
    return;
}
int confirm = JOptionPane.showConfirmDialog(this, "Delete this repair?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement("DELETE FROM repair WHERE repair_id=?")) {
    ps.setInt(1, id);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

