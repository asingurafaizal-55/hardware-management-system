private void runReport(String title, String sql, String fileName) {
    JFileChooser fc = new JFileChooser();
    fc.setSelectedFile(new java.io.File(fileName));
    if (fc.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) return;
    java.io.File out = fc.getSelectedFile();
    if (!out.getName().toLowerCase().endsWith(".pdf")) {
        out = new java.io.File(out.getAbsolutePath() + ".pdf");
    }
    try {
        db.ReportGenerator.generate(title, sql, out);
        JOptionPane.showMessageDialog(this, "Report saved:\n" + out.getAbsolutePath());
        java.awt.Desktop.getDesktop().open(out);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Could not create the report: " + e.getMessage());
    }
}

