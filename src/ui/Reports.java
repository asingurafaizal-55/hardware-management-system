    private void btnInventoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInventoryActionPerformed
runReport("Hardware Inventory Report",
    "SELECT h.hardware_id AS `ID`, h.hardware_name AS `Hardware`, c.category_name AS `Category`, "
    + "b.brand_name AS `Brand`, h.model AS `Model`, h.unit_price AS `Unit Price`, "
    + "COALESCE(SUM(s.quantity_available), 0) AS `In Stock` "
    + "FROM hardware h "
    + "LEFT JOIN category c ON c.category_id = h.category_id "
    + "LEFT JOIN brand b ON b.brand_id = h.brand_id "
    + "LEFT JOIN stock s ON s.hardware_id = h.hardware_id "
    + "GROUP BY h.hardware_id, h.hardware_name, c.category_name, b.brand_name, h.model, h.unit_price "
    + "ORDER BY h.hardware_name",
    "Hardware_Inventory_Report.pdf");        // TODO add your handling code here:
    }//GEN-LAST:event_btnInventoryActionPerformed

