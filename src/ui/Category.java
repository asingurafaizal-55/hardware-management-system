    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer id = currentId();
if (id == null || txtName.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Enter a numeric Category ID and a Category Name");
    return;
}
try (Connection con = DBConnection.getConnection()) {
    PreparedStatement up = con.prepareStatement(
        "UPDATE category SET category_name=?, description=? WHERE category_id=?");
    up.setString(1, txtName.getText().trim());
    up.setString(2, txtDescription.getText().trim());
    up.setInt(3, id);
    if (up.executeUpdate() == 0) {
        PreparedStatement ins = con.prepareStatement(
            "INSERT INTO category (category_id, category_name, description) VALUES (?, ?, ?)");
        ins.setInt(1, id);
        ins.setString(2, txtName.getText().trim());
        ins.setString(3, txtDescription.getText().trim());
        ins.executeUpdate();
    }
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer id = currentId();
if (id == null) {
    JOptionPane.showMessageDialog(this, "Find or select a record first");
    return;
}
int confirm = JOptionPane.showConfirmDialog(this, "Delete this category?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement("DELETE FROM category WHERE category_id=?")) {
    ps.setInt(1, id);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

