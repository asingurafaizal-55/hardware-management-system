    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer id = currentId();
Integer hwId = comboId(cmbHardware);
if (id == null || hwId == null) {
    JOptionPane.showMessageDialog(this, "Enter a numeric Specification ID and choose a hardware item");
    return;
}
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "INSERT INTO hardware_specification (specification_id, hardware_id, processor, ram, storage, operating_system) "
        + "VALUES (?, ?, ?, ?, ?, ?) AS v ON DUPLICATE KEY UPDATE hardware_id=v.hardware_id, "
        + "processor=v.processor, ram=v.ram, storage=v.storage, operating_system=v.operating_system")) {
    ps.setInt(1, id);
    ps.setInt(2, hwId);
    ps.setString(3, txtProcessor.getText().trim());
    ps.setString(4, txtRam.getText().trim());
    ps.setString(5, txtStorage.getText().trim());
    ps.setString(6, txtOS.getText().trim());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer id = currentId();
if (id == null) {
    JOptionPane.showMessageDialog(this, "Find or select a record first");
    return;
}
int confirm = JOptionPane.showConfirmDialog(this, "Delete this hardware_specification?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement("DELETE FROM hardware_specification WHERE specification_id=?")) {
    ps.setInt(1, id);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

