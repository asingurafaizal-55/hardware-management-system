    private void loadCombo(javax.swing.JComboBox<String> box, String sql) {
    box.removeAllItems();
    try (Connection con = DBConnection.getConnection();
         Statement st = con.createStatement();
         ResultSet rs = st.executeQuery(sql)) {
        while (rs.next()) {
            box.addItem(rs.getInt(1) + " - " + rs.getString(2));
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    box.setSelectedIndex(-1);
}

private Integer comboId(javax.swing.JComboBox<String> box) {
    Object item = box.getSelectedItem();
    if (item == null) return null;
    return Integer.valueOf(item.toString().split(" - ")[0]);
}

private void selectCombo(javax.swing.JComboBox<String> box, int id) {
    for (int i = 0; i < box.getItemCount(); i++) {
        if (box.getItemAt(i).startsWith(id + " - ")) {
            box.setSelectedIndex(i);
            return;
        }
    }
    box.setSelectedIndex(-1);
}
    private void clearFields() {
    txtId.setText("");
    cmbHardware.setSelectedIndex(-1);
    txtProcessor.setText("");
    txtRam.setText("");
    txtStorage.setText("");
    txtOS.setText("");
}
    

private Integer currentId() {
    try {
        return Integer.valueOf(txtId.getText().trim());
    } catch (NumberFormatException e) {
        return null;
    }
}

private void showRecord(String sql, Object... params) {
    try (Connection con = DBConnection.getConnection();
         PreparedStatement ps = con.prepareStatement(sql)) {
        for (int i = 0; i < params.length; i++) {
            ps.setObject(i + 1, params[i]);
        }
        try (ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                txtId.setText(String.valueOf(rs.getInt("specification_id")));
selectCombo(cmbHardware, rs.getInt("hardware_id"));
txtProcessor.setText(rs.getString("processor"));
txtRam.setText(rs.getString("ram"));
txtStorage.setText(rs.getString("storage"));
txtOS.setText(rs.getString("operating_system"));
            } else {
                JOptionPane.showMessageDialog(this, "No record found");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
    

