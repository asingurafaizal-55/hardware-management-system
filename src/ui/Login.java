    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
String user = txtUsername.getText().trim();
String pw = new String(txtPassword.getPassword());
if (user.isEmpty() || pw.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Enter your username and password");
    return;
}
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "SELECT password, role, account_status FROM user_account WHERE username=?")) {
    ps.setString(1, user);
    try (ResultSet rs = ps.executeQuery()) {
        if (rs.next() && pw.equals(rs.getString("password"))) {
            String status = rs.getString("account_status");
            if (status != null && !status.equalsIgnoreCase("Active")) {
                JOptionPane.showMessageDialog(this, "This account is not active");
                return;
            }
            new Menu(rs.getString("role")).setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Wrong username or password");
        }
    }
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnLoginActionPerformed

