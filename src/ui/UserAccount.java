    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
Integer id = currentId();
Integer empId = comboId(cmbEmployee);
if (id == null || empId == null || txtUsername.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Enter a numeric User ID and a username, and choose an employee");
    return;
}
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement(
        "INSERT INTO user_account (user_id, employee_id, username, password, role, account_status) "
        + "VALUES (?, ?, ?, ?, ?, ?) AS v ON DUPLICATE KEY UPDATE employee_id=v.employee_id, "
        + "username=v.username, password=v.password, role=v.role, account_status=v.account_status")) {
    ps.setInt(1, id);
    ps.setInt(2, empId);
    ps.setString(3, txtUsername.getText().trim());
    ps.setString(4, new String(txtPassword.getPassword()));
    ps.setString(5, txtRole.getText().trim());
    ps.setString(6, txtStatus.getText().trim());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Saved");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
Integer id = currentId();
if (id == null) {
    JOptionPane.showMessageDialog(this, "Find or select a record first");
    return;
}
int confirm = JOptionPane.showConfirmDialog(this, "Delete this user_account?", "Confirm", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;
try (Connection con = DBConnection.getConnection();
     PreparedStatement ps = con.prepareStatement("DELETE FROM user_account WHERE user_id=?")) {
    ps.setInt(1, id);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Deleted");
    clearFields();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

